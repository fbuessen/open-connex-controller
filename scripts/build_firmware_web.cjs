#!/usr/bin/env node
// Mechanical asset embedding only. --check never writes and detects stale builds.
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '../src/firmware');
const assets = [['kIndex','index.html','HTML'],['kStyle','style.css','CSS'],['kScript','app.js','JS'],['kFavicon','favicon.svg','SVG']];
let output = '// Generated by scripts/build_firmware_web.cjs. Edit web/ sources.\n#pragma once\n#include <Arduino.h>\nnamespace firmware {\n';
for (const [name, file, delimiter] of assets) {
  const source = fs.readFileSync(path.join(root, 'web', file), 'utf8');
  if (source.includes(')' + delimiter + '"')) throw new Error('Raw string delimiter in ' + file);
  output += `const char ${name}[] PROGMEM = R"${delimiter}(${source})${delimiter}";\n`;
}
output += '}\n';
const destination = path.join(root, 'web_assets.h');
if (process.argv.includes('--check')) {
  if (fs.readFileSync(destination, 'utf8') !== output) throw new Error('Stale firmware assets: run node scripts/build_firmware_web.cjs');
  console.log('PASS: embedded assets match web sources');
} else { fs.writeFileSync(destination, output); console.log('Embedded firmware web assets'); }
